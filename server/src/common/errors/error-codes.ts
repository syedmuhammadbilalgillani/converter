import { HttpStatus } from '@nestjs/common';

export enum AppErrorCode {
  FILE_TOO_LARGE = 'FILE_TOO_LARGE',
  UNSUPPORTED_FORMAT = 'UNSUPPORTED_FORMAT',
  FILE_NOT_FOUND = 'FILE_NOT_FOUND',
  CONVERSION_FAILED = 'CONVERSION_FAILED',
  INVALID_DIMENSIONS = 'INVALID_DIMENSIONS',
  INVALID_QUALITY = 'INVALID_QUALITY',
  BATCH_TOO_LARGE = 'BATCH_TOO_LARGE',
  JOB_NOT_FOUND = 'JOB_NOT_FOUND',
}

export const ERROR_HTTP_STATUS: Record<AppErrorCode, HttpStatus> = {
  [AppErrorCode.FILE_TOO_LARGE]: HttpStatus.PAYLOAD_TOO_LARGE,
  [AppErrorCode.UNSUPPORTED_FORMAT]: HttpStatus.UNPROCESSABLE_ENTITY,
  [AppErrorCode.FILE_NOT_FOUND]: HttpStatus.NOT_FOUND,
  [AppErrorCode.CONVERSION_FAILED]: HttpStatus.UNPROCESSABLE_ENTITY,
  [AppErrorCode.INVALID_DIMENSIONS]: HttpStatus.BAD_REQUEST,
  [AppErrorCode.INVALID_QUALITY]: HttpStatus.BAD_REQUEST,
  [AppErrorCode.BATCH_TOO_LARGE]: HttpStatus.BAD_REQUEST,
  [AppErrorCode.JOB_NOT_FOUND]: HttpStatus.NOT_FOUND,
};
